package com.comp2042.core.logic.bricks;

/**
 * An enumeration of the standard Tetris brick types.
 */
public enum BrickType {
    /** Represents the I-shaped Tetris brick (straight block). */
    I,
    /** Represents the J-shaped Tetris brick. */
    J,
    /** Represents the L-shaped Tetris brick. */
    L,
    /** Represents the O-shaped Tetris brick (square block). */
    O,
    /** Represents the S-shaped Tetris brick. */
    S,
    /** Represents the T-shaped Tetris brick. */
    T,
    /** Represents the Z-shaped Tetris brick. */
    Z
}
